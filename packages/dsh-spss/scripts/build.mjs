/**
 * Build the browser bundle for the client half.
 *
 * Output contract (client-modules): a single script that calls
 * `window.__ModuleLoader__.load({ id, factory })`, where `factory(require)`
 * returns `{ name, inject, apply }`. React and react-dom stay external because
 * the host module table already owns them — bundling a second copy would
 * break hooks across the slot boundary.
 *
 * esbuild is resolved from the profile's installed `dsh-notes` dependency
 * tree, which is how this machine already builds DSH client plugins; set
 * `DSH_ESBUILD` to point elsewhere. Nothing is downloaded.
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { createRequire } from 'node:module'
import path from 'node:path'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const entry = path.join(root, 'src', 'bundle-entry.js')
// package.json declares `exports["./client"] -> "./lib/client.js"` and
// `dsh.client.platform = "web"`, matching the layout of the other sidebar
// plugins in this suite.
const outfile = path.join(root, 'lib', 'client.js')
const PLUGIN_ID = 'dsh-spss'

/** Where this machine's esbuild lives, in probe order. */
function esbuildCandidates() {
  const fromEnv = process.env.DSH_ESBUILD
  const profile = process.env.DSH_PROFILE_DIR
  const candidates = []
  if (fromEnv) candidates.push(fromEnv)
  if (profile) {
    candidates.push(
      path.join(profile, 'node_modules', 'dsh-notes', 'node_modules', 'esbuild', 'lib', 'main.js'),
      path.join(profile, 'node_modules', 'esbuild', 'lib', 'main.js'),
    )
  }
  return candidates
}

/** Load esbuild's JS API from the first candidate that resolves. */
async function loadEsbuild() {
  for (const candidate of esbuildCandidates()) {
    try {
      const module = await import(pathToFileURL(candidate).href)
      if (typeof module.build === 'function') return { build: module.build, from: candidate }
    } catch {
      // Try the next location.
    }
    try {
      const require = createRequire(pathToFileURL(path.dirname(candidate) + path.sep))
      const resolved = require.resolve('esbuild')
      const module = await import(pathToFileURL(resolved).href)
      if (typeof module.build === 'function') return { build: module.build, from: resolved }
    } catch {
      // Try the next location.
    }
  }
  throw new Error(
    'esbuild was not found. Install it in the DSH profile, or set DSH_ESBUILD ' +
      'to the esbuild lib/main.js path.',
  )
}

const { build, from } = await loadEsbuild()

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120', 'safari17', 'firefox120'],
  jsx: 'automatic',
  jsxImportSource: 'react',
  // JSX lives in .js sources; nothing else in src/ uses .js for a non-JSX file.
  loader: { '.js': 'jsx' },
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  legalComments: 'inline',
  logLevel: 'warning',
  metafile: true,
  minify: false,
  sourcemap: false,
  charset: 'utf8',
})

const [output] = result.outputFiles
const banner = [
  '/* dsh-spss — SPSS-style statistical analysis inside the DSH sidebar.',
  ' * Generated by scripts/build.mjs from src/ — edit the source, not this file. */',
  '',
].join('\n')

const wrapped = `${banner}window.__ModuleLoader__.load({
\tid: ${JSON.stringify(PLUGIN_ID)},
\tfactory: function (require) {
\t\t"use strict";
\t\tvar exports = {};
\t\tvar module = { exports: exports };
${output.text.replace(/^/gm, '\t\t')}
\t\treturn module.exports;
\t},
});
`

await mkdir(path.dirname(outfile), { recursive: true })
await writeFile(outfile, wrapped, 'utf8')

const bytes = Buffer.byteLength(wrapped)
console.log(`esbuild: ${from}`)
console.log(`entry:   ${path.relative(root, entry)}`)
console.log(`wrote:   ${path.relative(root, outfile)} (${(bytes / 1024).toFixed(1)} KiB, ${bytes} bytes)`)
