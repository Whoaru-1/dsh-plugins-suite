/**
 * Build the browser bundle for the client half.
 * Output contract: a script calling window.__ModuleLoader__.load({ id, factory }).
 */
import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const result = await build({
  entryPoints: [path.join(root, 'src', 'bundle-entry.js')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120', 'safari17', 'firefox120'],
  jsx: 'automatic',
  jsxImportSource: 'react',
  loader: { '.js': 'jsx' },
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  legalComments: 'inline',
  logLevel: 'info',
  minify: false,
  charset: 'utf8'
})
const [output] = result.outputFiles
const wrapped = `/* dsh-deploy — generated by scripts/build.mjs; edit src/ instead. */
window.__ModuleLoader__.load({
\tid: "dsh-deploy",
\tfactory: function (require) {
\t\t"use strict";
\t\tvar exports = {};
\t\tvar module = { exports: exports };
${output.text.replace(/^/gm, '\t\t')}
\t\treturn module.exports;
\t},
});
`
await mkdir(path.join(root, 'lib'), { recursive: true })
await writeFile(path.join(root, 'lib', 'client.js'), wrapped, 'utf8')
console.log(`wrote lib/client.js (${(Buffer.byteLength(wrapped) / 1024).toFixed(0)} KiB)`)
