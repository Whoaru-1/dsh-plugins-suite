/**
 * Build the browser bundle for the client half.
 *
 * Output contract (client-modules): a single script that calls
 * `window.__ModuleLoader__.load({ id, factory })`, where `factory(require)`
 * returns `{ name, inject, apply }`. React and react-dom stay external because
 * the module table already owns them; every renderer library is bundled in.
 */
import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const entry = path.join(root, 'src', 'bundle-entry.js')
const outfile = path.join(root, 'lib', 'client.js')
const PLUGIN_ID = 'dsh-office-preview'

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120', 'safari17', 'firefox120'],
  jsx: 'automatic',
  jsxImportSource: 'react',
  // This plugin keeps JSX inside .js sources; nothing else uses .js in src/.
  loader: { '.js': 'jsx' },
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  legalComments: 'inline',
  logLevel: 'info',
  metafile: true,
  minify: false,
  sourcemap: false,
  charset: 'utf8',
})

const [output] = result.outputFiles
const banner = [
  '/* dsh-office-preview — bundled document renderers for the DSH sidebar preview.',
  ' * Libraries: docx-preview (Apache-2.0), SheetJS xlsx (Apache-2.0), pptx-preview (ISC).',
  ' * Generated by scripts/build.mjs — edit src/ instead. */',
  '',
].join('\n')

const wrapped = `${banner}window.__ModuleLoader__.load({
	id: ${JSON.stringify(PLUGIN_ID)},
	factory: function (require) {
		"use strict";
		var exports = {};
		var module = { exports: exports };
${output.text.replace(/^/gm, '\t\t')}
		return module.exports;
	},
});
`

await mkdir(path.dirname(outfile), { recursive: true })
await writeFile(outfile, wrapped, 'utf8')

const bytes = Buffer.byteLength(wrapped)
const inputs = Object.entries(result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].inputs)
  .map(([name, meta]) => [name, meta.bytesInOutput])
  .sort((a, b) => b[1] - a[1])
console.log(`\nwrote ${path.relative(root, outfile)} (${(bytes / 1024).toFixed(0)} KiB)`)
for (const [name, size] of inputs.slice(0, 12)) {
  console.log(`  ${(size / 1024).toFixed(0).padStart(6)} KiB  ${name}`)
}
